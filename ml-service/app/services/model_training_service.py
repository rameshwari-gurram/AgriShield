def train_and_calibrate_final_model(
    df_features: pd.DataFrame,
    df_metadata: pd.DataFrame,
    hyperparams: Optional[ModelHyperparameters] = None,
    n_splits: int = 5,
    calib_fold_index: int = 0,
    random_state: int = 42,
) -> Tuple[HistGradientBoostingClassifier, CalibratedClassifierCV, Dict[str, Any]]:
    """
    Trains the final baseline HistGradientBoostingClassifier and applies
    group-safe probability calibration (Platt scaling) via CalibratedClassifierCV.

    Architectural Safeguards:
    1. The 50 scenarios are partitioned into Base Model Training Scenarios (e.g. 40 groups)
       and Probability Calibration Scenarios (e.g. 10 groups).
    2. Base model M_base is fitted EXCLUSIVELY on Base Training Scenarios.
    3. CalibratedClassifierCV(cv='prefit', method='sigmoid') is fitted EXCLUSIVELY
       on Calibration Scenarios.
    4. Assert train_scenarios ∩ calib_scenarios == empty.
    5. Native NaNs are preserved across both base and calibrated models.
    """
    if hyperparams is None:
        hyperparams = ModelHyperparameters(random_state=random_state)

    X = df_features[FEATURE_NAMES].to_numpy()
    y = df_metadata["target_severe_water_stress"].to_numpy(dtype=np.int32)
    groups = df_metadata["scenario_id"].to_numpy(dtype=np.int32)

    sgkf = StratifiedGroupKFold(n_splits=n_splits, shuffle=True, random_state=random_state)
    splits = list(sgkf.split(X, y, groups))

    train_idx, calib_idx = splits[calib_fold_index]
    train_scenarios = set(groups[train_idx])
    calib_scenarios = set(groups[calib_idx])

    # Assert strict scenario group isolation
    if not train_scenarios.isdisjoint(calib_scenarios):
        raise RuntimeError("FATAL: Group leakage between base training scenarios and calibration scenarios!")

    # Data slices using DataFrame to preserve feature names
    X_df = df_features[FEATURE_NAMES]
    X_train, y_train = X_df.iloc[train_idx], y[train_idx]
    X_calib, y_calib = X_df.iloc[calib_idx], y[calib_idx]

    # 1. Fit Base Model
    base_model = HistGradientBoostingClassifier(**hyperparams.to_dict())
    base_model.fit(X_train, y_train)

    # 2. Fit Group-Safe Calibrator (prefit Platt scaling)
    calibrated_model = CalibratedClassifierCV(estimator=base_model, cv="prefit", method="sigmoid")
    calibrated_model.fit(X_calib, y_calib)

    # 3. Evaluate calibration impact on the held-out calibration scenarios
    raw_probs = base_model.predict_proba(X_calib)[:, 1]
    cal_probs = calibrated_model.predict_proba(X_calib)[:, 1]

    uncal_brier = float(brier_score_loss(y_calib, raw_probs))
    cal_brier = float(brier_score_loss(y_calib, cal_probs))
    cal_auc = float(roc_auc_score(y_calib, cal_probs))

    calibration_audit = {
        "train_rows": len(train_idx),
        "calib_rows": len(calib_idx),
        "train_scenario_count": len(train_scenarios),
        "calib_scenario_count": len(calib_scenarios),
        "train_scenarios_list": [int(x) for x in sorted(list(train_scenarios))],
        "calib_scenarios_list": [int(x) for x in sorted(list(calib_scenarios))],
        "uncalibrated_brier_score": round(uncal_brier, 5),
        "calibrated_brier_score": round(cal_brier, 5),
        "brier_score_reduction": round(uncal_brier - cal_brier, 5),
        "diagnostic_type": "calibration_set_fit_diagnostic",
        "diagnostic_note": (
            "Platt scaling fit diagnostic evaluated on the held-out scenarios used to fit the sigmoid parameters. "
            "Not an independent estimate of calibrated probability generalization."
        ),
        "calibrated_auc": round(cal_auc, 4),
    }

    return base_model, calibrated_model, calibration_audit


