def verify_shap_compatibility(
    base_model: HistGradientBoostingClassifier,
    X_sample: np.ndarray,
) -> Dict[str, Any]:
    """
    Executes a SHAP TreeExplainer compatibility smoke test against the trained HGB model.

    Verifies:
    1. shap.TreeExplainer initializes with the model.
    2. Output shape matches (n_samples, 17).
    3. All SHAP values are finite.
    4. Exact log-odds additivity: sum(SHAP) + base_value == decision_function(X).
    """
    shap = get_shap_module()

    explainer = shap.TreeExplainer(base_model)
    explanation = explainer(X_sample)

    shap_vals = explanation.values
    base_vals = explanation.base_values
    n_samples, n_feats = shap_vals.shape

    if n_feats != 17:
        raise ValueError(f"SHAP explanation feature dimension expected 17, got {n_feats}")

    # Check finite
    if not np.isfinite(shap_vals).all():
        raise ValueError("Non-finite values encountered in SHAP explanation!")

    # Check log-odds additivity against decision_function
    raw_margins = base_model.decision_function(X_sample)
    reconstructed_margins = np.sum(shap_vals, axis=1) + base_vals
    max_additivity_error = float(np.max(np.abs(raw_margins - reconstructed_margins)))

    if max_additivity_error > 1e-7:
        raise ValueError(
            f"SHAP log-odds additivity failed! Max error {max_additivity_error:.2e} exceeds tolerance 1e-7"
        )

    return {
        "explainer_class": str(type(explainer)),
        "sample_count": n_samples,
        "feature_count": n_feats,
        "max_additivity_error": max_additivity_error,
        "additivity_verified": True,
        "explains_margin_not_probability": True,
    }


