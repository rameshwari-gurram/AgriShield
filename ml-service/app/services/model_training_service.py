# GROUPED CROSS-VALIDATION
# =============================================================================

def run_grouped_cross_validation(
    df_features: pd.DataFrame,
    df_metadata: pd.DataFrame,
    hyperparams: Optional[ModelHyperparameters] = None,
    n_splits: int = 5,
    random_state: int = 42,
) -> Tuple[List[FoldMetrics], Dict[str, Any], np.ndarray, np.ndarray]:
    """
    Executes 5-fold StratifiedGroupKFold cross-validation on the 17-feature matrix.

    Invariants Enforced:
    1. df_features must have exactly 17 columns matching FEATURE_NAMES.
    2. Zero scenario overlap: train_scenarios ∩ val_scenarios == empty for every fold.
    3. Exactly one out-of-fold prediction generated for every single row.
    4. Group variable is strictly scenario_id.

    Returns:
        fold_metrics: List of metrics for each fold
        pooled_oof_metrics: Aggregate performance metrics across all out-of-fold predictions
        oof_probabilities: Array of out-of-fold predicted probabilities P(y=1)
        oof_predictions: Array of out-of-fold predicted binary labels
    """
    # 1. Feature contract validation
    if list(df_features.columns) != FEATURE_NAMES:
        raise ValueError(
            f"Feature contract violation! Expected {len(FEATURE_NAMES)} features in contract order, "
            f"got {list(df_features.columns)}"
        )

    # 2. Extract arrays
    X = df_features[FEATURE_NAMES].to_numpy()
    y = df_metadata["target_severe_water_stress"].to_numpy(dtype=np.int32)
    groups = df_metadata["scenario_id"].to_numpy(dtype=np.int32)

    N = len(df_features)
    if hyperparams is None:
        hyperparams = ModelHyperparameters(random_state=random_state)

    # 3. Setup StratifiedGroupKFold
    sgkf = StratifiedGroupKFold(n_splits=n_splits, shuffle=True, random_state=random_state)

    oof_probabilities = np.full(N, np.nan, dtype=np.float64)
    oof_predictions = np.full(N, -1, dtype=np.int32)
    val_scenario_tracker: Set[int] = set()
    fold_metrics_list: List[FoldMetrics] = []

    for fold_idx, (train_idx, val_idx) in enumerate(sgkf.split(X, y, groups), start=1):
        train_scenarios = set(groups[train_idx])
        val_scenarios = set(groups[val_idx])

        # INVARIANT 1: Zero Scenario Overlap
        overlap = train_scenarios.intersection(val_scenarios)
        if len(overlap) > 0:
            raise RuntimeError(
                f"FATAL: Scenario leakage detected in Fold {fold_idx}! "
                f"Scenarios present in both train and validation: {overlap}"
            )

        # INVARIANT 2: Every scenario validated exactly once
        scenario_leakage = val_scenarios.intersection(val_scenario_tracker)
        if len(scenario_leakage) > 0:
            raise RuntimeError(
                f"FATAL: Scenario evaluated multiple times across folds: {scenario_leakage}"
            )
        val_scenario_tracker.update(val_scenarios)

        # Data slices
        X_train, y_train = X[train_idx], y[train_idx]
        X_val, y_val = X[val_idx], y[val_idx]

        # Fit model on training slice
        model = HistGradientBoostingClassifier(**hyperparams.to_dict())
        model.fit(X_train, y_train)

        # Predict on validation slice
        val_probs = model.predict_proba(X_val)[:, 1]
        val_preds = model.predict(X_val)

        # Store OOF predictions
        oof_probabilities[val_idx] = val_probs
        oof_predictions[val_idx] = val_preds

        # Compute fold metrics
        # Check if ROC AUC is mathematically defined (requires at least one positive and one negative)
        if len(np.unique(y_val)) > 1:
            fold_auc = float(roc_auc_score(y_val, val_probs))
            fold_pr_auc = float(average_precision_score(y_val, val_probs))
        else:
            fold_auc = float("nan")
            fold_pr_auc = float("nan")

        fold_acc = float(accuracy_score(y_val, val_preds))
        fold_prec = float(precision_score(y_val, val_preds, zero_division=0))
        fold_rec = float(recall_score(y_val, val_preds, zero_division=0))
        fold_f1 = float(f1_score(y_val, val_preds, zero_division=0))
        fold_cm = confusion_matrix(y_val, val_preds, labels=[0, 1]).tolist()

        metric = FoldMetrics(
            fold=fold_idx,
            train_rows=len(train_idx),
            val_rows=len(val_idx),
            train_scenarios=len(train_scenarios),
            val_scenarios=len(val_scenarios),
            train_pos=int(np.sum(y_train == 1)),
            train_neg=int(np.sum(y_train == 0)),
            val_pos=int(np.sum(y_val == 1)),
            val_neg=int(np.sum(y_val == 0)),
            val_prevalence=float(np.mean(y_val)),
            roc_auc=round(fold_auc, 4),
            pr_auc=round(fold_pr_auc, 4),
            accuracy=round(fold_acc, 4),
            precision=round(fold_prec, 4),
            recall=round(fold_rec, 4),
            f1=round(fold_f1, 4),
            confusion_matrix=fold_cm,
        )
        fold_metrics_list.append(metric)

    # INVARIANT 3: Complete OOF coverage
    if np.isnan(oof_probabilities).any():
        raise RuntimeError("FATAL: Incomplete OOF coverage! NaN values found in out-of-fold probabilities.")
    if (oof_predictions == -1).any():
        raise RuntimeError("FATAL: Incomplete OOF coverage! Unassigned rows found in out-of-fold predictions.")

    # 4. Compute Pooled Out-of-Fold Metrics
    pooled_auc = float(roc_auc_score(y, oof_probabilities))
    pooled_pr_auc = float(average_precision_score(y, oof_probabilities))
    pooled_acc = float(accuracy_score(y, oof_predictions))
    pooled_prec = float(precision_score(y, oof_predictions, zero_division=0))
    pooled_rec = float(recall_score(y, oof_predictions, zero_division=0))
    pooled_f1 = float(f1_score(y, oof_predictions, zero_division=0))
    pooled_brier = float(brier_score_loss(y, oof_probabilities))
    pooled_cm = confusion_matrix(y, oof_predictions, labels=[0, 1]).tolist()

    pooled_oof_metrics = {
        "total_rows": N,
        "total_scenarios": int(df_metadata["scenario_id"].nunique()),
        "overall_prevalence": float(np.mean(y)),
        "roc_auc": round(pooled_auc, 4),
        "pr_auc": round(pooled_pr_auc, 4),
        "accuracy": round(pooled_acc, 4),
        "precision": round(pooled_prec, 4),
        "recall": round(pooled_rec, 4),
        "f1": round(pooled_f1, 4),
        "brier_score": round(pooled_brier, 4),
        "confusion_matrix": pooled_cm,
    }

    return fold_metrics_list, pooled_oof_metrics, oof_probabilities, oof_predictions


