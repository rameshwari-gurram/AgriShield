@dataclass(frozen=True)
class ModelHyperparameters:
    """Explicit hyperparameters for HistGradientBoostingClassifier."""
    max_iter: int = 100
    learning_rate: float = 0.05
    max_depth: int = 5
    min_samples_leaf: int = 20
    l2_regularization: float = 1.0
    random_state: int = 42

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class FoldMetrics:
    """Metrics for a single grouped cross-validation fold."""
    fold: int
    train_rows: int
    val_rows: int
    train_scenarios: int
    val_scenarios: int
    train_pos: int
    train_neg: int
    val_pos: int
    val_neg: int
    val_prevalence: float
    roc_auc: float
    pr_auc: float
    accuracy: float
    precision: float
    recall: float
    f1: float
    confusion_matrix: List[List[int]]

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


# =============================================================================
# SHAP SAFE IMPORT HELPER
# =============================================================================

def get_shap_module():
    """
    Safely imports shap, ensuring Windows Application Control policies that block
    numba's C-extension (_typeconv.pyd) do not block TreeExplainer execution.
    """
    if "numba" not in sys.modules:
        try:
            import numba  # Attempt standard import
        except Exception:
            # Fall back to lightweight stub for numba
            numba_mock = MagicMock()
            numba_mock.njit = lambda *args, **kwargs: (lambda f: f) if args and callable(args[0]) else (lambda f: f)
            numba_mock.jit = lambda *args, **kwargs: (lambda f: f) if args and callable(args[0]) else (lambda f: f)
            sys.modules["numba"] = numba_mock
            sys.modules["numba.typed"] = MagicMock()
    import shap
    return shap


