def _sanitize_for_json(obj: Any) -> Any:
    if isinstance(obj, (np.integer, int)):
        return int(obj)
    elif isinstance(obj, (np.floating, float)):
        return float(obj)
    elif isinstance(obj, np.ndarray):
        return obj.tolist()
    elif isinstance(obj, dict):
        return {str(k): _sanitize_for_json(v) for k, v in obj.items()}
    elif isinstance(obj, (list, tuple, set)):
        return [_sanitize_for_json(x) for x in obj]
    return obj


def save_model_artifacts(
    save_dir: str,
    base_model: HistGradientBoostingClassifier,
    calibrated_model: CalibratedClassifierCV,
    hyperparams: ModelHyperparameters,
    calibration_audit: Dict[str, Any],
    pooled_oof_metrics: Dict[str, Any],
    dataset_seed: int = 42,
) -> Dict[str, str]:
    """
    Persists trained base model, calibrated model, and metadata JSON.
    """
    os.makedirs(save_dir, exist_ok=True)

    base_model_path = os.path.join(save_dir, "base_model.joblib")
    calibrated_model_path = os.path.join(save_dir, "calibrated_model.joblib")
    metadata_path = os.path.join(save_dir, "model_metadata.json")

    # 1. Save models using joblib
    joblib.dump(base_model, base_model_path)
    joblib.dump(calibrated_model, calibrated_model_path)

    # 2. Package metadata
    metadata = {
        "model_name": "AgriShield-Risk-HGB-Prototype",
        "model_version": "1.0.0",
        "feature_contract_version": "v1.1",
        "feature_count": len(FEATURE_NAMES),
        "feature_names": FEATURE_NAMES,
        "hyperparameters": hyperparams.to_dict(),
        "dataset_seed": dataset_seed,
        "calibration_configuration": {
            "method": "sigmoid (Platt scaling)",
            "cv": "prefit",
            "group_isolated": True,
            "audit": calibration_audit,
        },
        "pooled_oof_performance": pooled_oof_metrics,
        "software_environment": {
            "python": sys.version.split()[0],
            "scikit_learn": importlib.metadata.version("scikit-learn"),
            "joblib": importlib.metadata.version("joblib"),
            "numpy": importlib.metadata.version("numpy"),
            "pandas": importlib.metadata.version("pandas"),
            "shap": importlib.metadata.version("shap"),
        },
    }

    sanitized_metadata = _sanitize_for_json(metadata)
    with open(metadata_path, "w", encoding="utf-8") as f:
        json.dump(sanitized_metadata, f, indent=2)

    return {
        "base_model_path": base_model_path,
        "calibrated_model_path": calibrated_model_path,
        "metadata_path": metadata_path,
    }


def load_model_artifacts(load_dir: str) -> Tuple[HistGradientBoostingClassifier, CalibratedClassifierCV, Dict[str, Any]]:
    """
    Loads persisted base model, calibrated model, and metadata.
    """
    base_model_path = os.path.join(load_dir, "base_model.joblib")
    calibrated_model_path = os.path.join(load_dir, "calibrated_model.joblib")
    metadata_path = os.path.join(load_dir, "model_metadata.json")

    if not os.path.exists(base_model_path):
        raise FileNotFoundError(f"Missing base model artifact at {base_model_path}")
    if not os.path.exists(calibrated_model_path):
        raise FileNotFoundError(f"Missing calibrated model artifact at {calibrated_model_path}")
    if not os.path.exists(metadata_path):
        raise FileNotFoundError(f"Missing metadata artifact at {metadata_path}")

    base_model = joblib.load(base_model_path)
    calibrated_model = joblib.load(calibrated_model_path)

    with open(metadata_path, "r", encoding="utf-8") as f:
        metadata = json.load(f)

    return base_model, calibrated_model, metadata
